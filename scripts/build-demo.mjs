#!/usr/bin/env node
/**
 * scripts/build-demo.mjs — produces a single self-contained HTML file with the
 * whole application inlined (CSS + ES modules concatenated, no network requests).
 *
 *     npm run demo  →  demo/notepads-for-linux-demo.html
 *
 * The result runs the full UI in any browser with no build step and no server.
 * Files opened in it live in memory / are downloaded, because a plain page has no
 * filesystem access; everything else (tabs, search, themes, diff, settings,
 * session, shortcuts) behaves exactly like the Tauri build.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(here, '..');
const SRC = path.join(ROOT, 'src');
const OUT_DIR = path.join(ROOT, 'demo');
const OUT_FILE = path.join(OUT_DIR, 'notepads-for-linux-demo.html');

// Dependency order matters: later modules reference earlier declarations.
const MODULES = ['icons.js', 'editor.js', 'bridge.js', 'diff.js', 'app.js'];

function stripModuleSyntax(code, file) {
  return code
    .replace(/^\s*import\s+[^;]*?from\s*['"][^'"]+['"]\s*;?\s*$/gm, '')
    .replace(/^\s*import\s*['"][^'"]+['"]\s*;?\s*$/gm, '')
    .replace(/^\s*export\s+(const|let|var|function|class|async)\s/gm, '$1 ')
    .replace(/^\s*export\s*\{[^}]*\}\s*;?\s*$/gm, '')
    .replace(/^\s*export\s+default\s+/gm, 'const __default__ = ')
    .trimEnd();
}

function bundle() {
  const parts = [];
  for (const file of MODULES) {
    const full = path.join(SRC, file);
    const code = stripModuleSyntax(readFileSync(full, 'utf8'), file);
    parts.push(`/* ============================== ${file} ============================== */\n${code}`);
  }
  // One IIFE-free module scope: every module shares a scope, exactly like the
  // concatenation the browser would do if the files were one script.
  return parts.join('\n\n');
}

function buildHtml() {
  const html = readFileSync(path.join(SRC, 'index.html'), 'utf8');
  const css = readFileSync(path.join(SRC, 'styles.css'), 'utf8');
  const js = bundle();

  const banner = `<!--
  Notepads for Linux — single file demo build (generated by scripts/build-demo.mjs)
  MIT licensed. An independent Linux remake of the Windows Notepads app by
  Jackie (Jiaqi) Liu (https://github.com/0x7c13/Notepads).
  Everything is inlined: this file works offline, from disk, with no server.
-->`;

  return html
    .replace(/^<!doctype html>/i, `<!doctype html>\n${banner}`)
    .replace(/<link[^>]*styles\.css[^>]*>/i, `<style>\n${css}\n</style>`)
    .replace(
      /<script[^>]*src="app\.js"[^>]*><\/script>/i,
      `<script type="module">\n${js}\n</script>`,
    );
}

mkdirSync(OUT_DIR, { recursive: true });
const output = buildHtml();
writeFileSync(OUT_FILE, output, 'utf8');
const kb = (Buffer.byteLength(output) / 1024).toFixed(1);
console.log(`demo written: ${path.relative(ROOT, OUT_FILE)} (${kb} KB, fully self-contained)`);

// Sanity checks: the module syntax must be gone and the script must be inline.
const problems = [];
if (/\bimport\s+.*from\s+['"]\.\//.test(output)) problems.push('leftover relative import');
if (/\bexport\s+(const|function|class)\b/.test(output)) problems.push('leftover export keyword');
if (!/<style>/.test(output)) problems.push('stylesheet was not inlined');
if (!/<script type="module">/.test(output)) problems.push('script was not inlined');
if (problems.length) {
  console.error('demo build FAILED: ' + problems.join('; '));
  process.exitCode = 1;
} else {
  console.log('demo build OK: no external references');
}
if (!existsSync(path.join(SRC, 'app.js'))) process.exit(1);
